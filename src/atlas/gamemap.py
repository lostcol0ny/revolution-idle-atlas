GAME_FILE_HEADER = (
    "# Generated by `atlas game` from a local game install, and committed.\n"
    "# `atlas build` overlays it on data/derived.yaml; data/relationships.yaml\n"
    "# still wins every field. Do not hand-edit: the next run overwrites it.\n"
)

# Unity rich text: <color=#fff>, </color>, <sprite name=x>, <pos=5%>, <s>. Only
# a tag-shaped run is dropped, so prose such as "<==" survives.
_TAG = re.compile(r"</?[A-Za-z][\w-]*(?:[= ][^<>]*)?>")
_LINE_BREAK = re.compile(r"<br\s*/?>", re.IGNORECASE)
_PLACEHOLDER = r"\{\d+(?::[^{}]*)?\}"
# A running total such as "(total: x{1})" is the player's state, not a
# description of the entity, so it goes rather than being reworded.
_RUNNING_TOTAL = re.compile(rf"\s*\((?:[^():]*:\s*)?[x+^-]?{_PLACEHOLDER}%?\)")
# The same, as a closing line: "... based on your IP.<br>Currently: x{0}".
_CURRENT_STATE = re.compile(
    rf"\s*Currently:\s*[x+^-]?{_PLACEHOLDER}(?:/{_PLACEHOLDER})?%?$"
)
# Most specific shape first: "x{0}%" is still a multiplier, "+{0}%" a percentage.
_PHRASES = (
    (re.compile(rf"(?<![A-Za-z])x{_PLACEHOLDER}%?"), "a multiplier"),
    (re.compile(rf"\^{_PLACEHOLDER}"), "an exponent"),
    (re.compile(rf"/{_PLACEHOLDER}"), "a divisor"),
    (re.compile(rf"[+-]?{_PLACEHOLDER}%"), "a percentage"),
    (re.compile(rf"[+-]{_PLACEHOLDER}"), "an amount"),
    (re.compile(_PLACEHOLDER), "a value"),
)
# "#1 Ionized Speed", or "#1 IP Gain ({0})" where the game appends the level.
_NUMBERED = re.compile(r"#(?P<number>\d+)\s+(?P<title>.+?)(?:\s*\(\{\d+\}\))?")
_NON_ALNUM = re.compile(r"[^0-9a-z]")
# The wiki and the game spell some names differently ("Magestic Halberd" /
# "Majestic Halberd", "Lucky Luck Crystal" / "Lucky Crystal"); an index that
# has slipped pairs unrelated names, which score far below this.
SAME_NAME_RATIO = 0.8


@dataclass(frozen=True)
class Family:
    system: str
    id_prefix: str
    # True: entity n is `<id_prefix>-<n+1>`, as relics and challenges are
    # numbered. False: matched by name among the system's `<id_prefix>-*` nodes.
    by_index: bool
    # The kind to create a node with when no node matches; None never creates.
    add_as: Kind | None
    # For names the game writes as "#<n> Title": the display name becomes
    # "<label> <n> (Title)", and the number, not the title, verifies the index.
    label: str | None = None


