# Particles keeps its text outside the _NAME_/_DESC_ pairs: one key per grade
# bonus, per Epsilon Tree effect and per spark colour.
GRADE_SYSTEM = "particles-grades"
_GRADE_BONUS_KEY = re.compile(r"PARTICLES_BONUS_(?P<grade>RANK|TIER|TETR|PENT)_(?P<index>\d+)")
# Only the 16 outer nodes have effect text: EPSILON_EFFECT_15..30 are A1..A16
# on the game's Epsilon Tree screen. The 15 inner nodes (B1-B8, C1-C4, D1, D2
# and the centre) share the template "Boosts {0} efficiency" and are curated.
EPSILON_TREE_SYSTEM = "epsilon-tree"
_EPSILON_EFFECT_KEY = re.compile(r"EPSILON_EFFECT_(?P<index>\d+)")
# The indices checked against the game screen. Anything outside, a new node a
# patch adds included, is reported until someone places it on the screen.
_OUTER_EFFECTS = range(15, 31)
SPARK_SYSTEM = "particles"
_SPARK_EFFECT_KEY = re.compile(r"ENUM_SPARKTYPE_EFFECT_(?P<colour>[A-Z]+)")
_SPARK_NAME = "UNI_PARTICLES_SPARK_NAME"
_GRADE_HEADER = re.compile(r"!.*\|\s*(?P<grade>Rank|Tier|Tetr|Pent) Bonuses")

# Achievements pair a name and a requirement (`ACH_NAME_<n>`, `ACH_DESC_<n>`)
# with an optional reward (`ACH_REWD_<n>`). Only those with a reward are mapped:
# the rest give Souls or Time Flux, which the wiki lists and the game words
# nowhere, so they would be nodes with no effect and no edge. A later
# achievement can swap a reward for `ACH_REWD_<n>_NEW` ("Changes the reward for
# Ach. 29"), which becomes the node's second effect.
ACHIEVEMENT_PREFIX = "ACH"
ACHIEVEMENT_SYSTEM = "achievements"
_ACHIEVEMENT_NAME_KEY = re.compile(r"ACH_NAME_(?P<index>\d+)")
_ACHIEVEMENT_REWARD_KEY = re.compile(r"ACH_REWD_(?P<index>\d+)")
# Secrets share the key space from 10000; the game counts both lists from 1.
_SECRET_BASE = 10000
_WIKI_ACHIEVEMENT = re.compile(r"\{\{Achievement/NormalRowItem(?P<body>.*?)\n\}\}", re.DOTALL)
# A threshold as the wiki writes one: "1,000,000", "1.08e308", "e5.00e10",
# "1e5000", "100 Qa".
_WIKI_AMOUNT = r"(e?\d[\d.,]*(?:e\d[\d.,]*)?(?: ?[A-Z][a-z]?)?)"


@dataclass
class FamilyReport:
    matched: int = 0
    added: int = 0
    unmatched: list[str] = field(default_factory=list)
    # A match whose game name differs from the node's current name.
    renamed: list[str] = field(default_factory=list)
    # Entities the family deliberately leaves out, such as rewardless achievements.
    left_out: int = 0


def clean(text: str) -> str:
    """Drop Unity rich-text tags and collapse whitespace."""
    return " ".join(_TAG.sub("", _LINE_BREAK.sub(" ", text)).split())


def readable(text: str, *, formulas: bool = False) -> str:
    """Clean a description and word its runtime placeholders.

    The game fills `{0}` in at runtime, so a bare token tells a reader
    nothing; the symbol beside it says what sort of number it is. `formulas`
    typesets the arithmetic a description spells out in plain text (see
    `typeset`); without it the whole text stays prose.
    """
    text = _CURRENT_STATE.sub("", _RUNNING_TOTAL.sub("", clean(text)))
    for pattern, phrase in _PHRASES:
        text = pattern.sub(phrase, text)
    # Same text format as wiki prose: `$` would otherwise open inline math.
    return typeset(text) if formulas else escape_prose(text)


# The grade bonuses write their formulas in plain text: "×(1 + 0.05 × rank)",
# "(gain × 100)^(1 + 0.1 × pent) / 100". A grade is an operand anywhere. The
# other words are operands only inside parentheses, because outside them they
# are the prose a formula sits in: "Attack gold gain ^(1 + 0.01 × tetr)".
_FORMULA_TOKEN = re.compile(
    r"\s*(?:"
    r"(?P<func>(?i:sqrt))(?=\()"
    r"|(?<![\w.])(?P<grade>(?i:rank|tier|tetr|pent))(?!\w)"
    r"|(?<![\w.])(?P<word>equipped ER level|generator level|multiplier level|gain|[αβγδ])(?!\w)"
    r"|(?<![\w.])(?P<num>\d+(?:\.\d+)?)(?!\w)"
    r"|(?P<op>[×+\-/^]|(?<=\s)x(?=\s))"
    r"|(?P<open>\()|(?P<close>\))"
    r")"
)
_OPERAND_START = frozenset({"func", "grade", "word", "num", "open"})
_OPERAND_END = frozenset({"grade", "word", "num", "close"})
# Operators that may open a formula: "×(1 + 0.1 × tier)", "^(1 + 0.2 × tetr)",
# "speed + 0.01 x Sqrt(rank)". The formula is what the prose before it gets.
_LEADING_OPS = frozenset("×^+")


@dataclass(frozen=True)
class _Token:
    kind: str
    text: str
    start: int
    end: int


def _formula_runs(text: str) -> list[list[_Token]]:
    """Maximal runs of formula tokens, split where two operands meet."""
    runs: list[list[_Token]] = []
    run: list[_Token] = []
    depth = 0
    pos = 0
    while pos < len(text):
        match = _FORMULA_TOKEN.match(text, pos)
        kind = match.lastgroup if match else None
        if kind == "word" and depth == 0:
            kind = None
        # "x" is a letter unless it stands between two operands.
        if kind == "op" and match and match["op"] == "x" and (
            not run or run[-1].kind not in _OPERAND_END
        ):
            kind = None
        if kind is None or match is None:
            if run:
                runs.append(run)
            run, depth = [], 0
            pos += 1
            continue
        if kind in _OPERAND_START and run and run[-1].kind in _OPERAND_END:
            # "tetr 10", "^0.2 (improved by ...)": no operator, so two runs.
            runs.append(run)
            run, depth = [], 0
            continue
        depth += {"open": 1, "close": -1}.get(kind, 0)
        run.append(_Token(kind, match[kind], match.start(kind), match.end(kind)))
        pos = match.end()
    if run:
        runs.append(run)
    return runs


def _trim(run: list[_Token]) -> list[_Token]:
    """Drop the edges of a run that cannot belong to its formula."""
    run = list(run)
    while run:
        opens = sum(t.kind == "open" for t in run)
        closes = sum(t.kind == "close" for t in run)
        first, last = run[0], run[-1]
        if (
            first.kind == "close"
            or (first.kind == "op" and first.text not in _LEADING_OPS)
            or (first.kind == "open" and opens > closes)
        ):
            run.pop(0)
        elif last.kind in ("open", "op", "func") or (last.kind == "close" and closes > opens):
            run.pop()
        else:
            break
    return run


def _is_formula(run: list[_Token]) -> bool:
    """True for well-formed arithmetic with at least one binary operator.

    A lone leading operator is the game's shorthand ("^1.1", "×tier",
    "+0.01 per rank") and stays prose.
    """
    depth = 0
    binary = False
    for i, token in enumerate(run):
        depth += {"open": 1, "close": -1}.get(token.kind, 0)
        if depth < 0:
            return False
        following = run[i + 1].kind if i + 1 < len(run) else None
        if token.kind == "func":
            if following != "open":
                return False
            binary = True
        elif token.kind == "op":
            if following not in _OPERAND_START:
                return False
            if i > 0:
                if run[i - 1].kind not in _OPERAND_END:
                    return False
                binary = True
    return depth == 0 and binary


def _operand_end(run: list[_Token], start: int) -> int:
    """The index just past the operand that begins at `start`."""
    end = start + 1 if run[start].kind == "func" else start
    if run[end].kind != "open":
        return end + 1
    depth = 0
    for i in range(end, len(run)):
        depth += {"open": 1, "close": -1}.get(run[i].kind, 0)
        if depth == 0:
            return i + 1
    raise AssertionError("unbalanced run passed _is_formula")


def _latex(run: list[_Token]) -> str:
    parts: list[str] = []
    i = 0
    while i < len(run):
        token = run[i]
        if token.kind == "func":
            end = _operand_end(run, i)
            parts.append(rf"\sqrt{{{_latex(run[i + 2 : end - 1])}}}")
            i = end
            continue
        if token.text == "^":
            end = _operand_end(run, i + 1)
            operand = run[i + 1 : end]
            # The braces group the exponent, so its parentheses are redundant.
            if operand[0].kind == "open":
                operand = operand[1:-1]
            parts.append(f"^{{{_latex(operand)}}}")
            i = end
            continue
        if token.kind in ("grade", "word") and token.text.isascii():
            parts.append(rf"\text{{{token.text}}}")
        elif token.text in ("×", "x"):
            parts.append(r"\times")
        else:
            parts.append(token.text)
        i += 1
    return " ".join(parts).replace("( ", "(").replace(" )", ")").replace(" ^{", "^{")


def typeset(text: str) -> str:
    """Escape prose, and turn the formulas in it into `$LaTeX$`.

    Conservative on purpose: only a balanced run of numbers, grades, a few
    known operand words and operators, with a binary operator in it, becomes
    math. Anything else stays prose exactly as the game wrote it.
    """
    out: list[str] = []
    pos = 0
    for raw in _formula_runs(text):
        run = _trim(raw)
        if not _is_formula(run):
            continue
        start, end = run[0].start, run[-1].end
        out += [escape_prose(text[pos:start]), f"${_latex(run)}$"]
        pos = end
    out.append(escape_prose(text[pos:]))
    return "".join(out)


def _norm(name: str) -> str:
    return _NON_ALNUM.sub("", name.casefold())


def _same_name(a: str, b: str) -> bool:
    return SequenceMatcher(None, _norm(a), _norm(b)).ratio() >= SAME_NAME_RATIO


def _map_family(
    family: Family, entries: Iterable[Mapping[str, Any]], nodes: Mapping[str, Node]
) -> tuple[list[GameNode], FamilyReport]:
    members = [
        n
        for n in nodes.values()
        if n.system == family.system and n.id.startswith(f"{family.id_prefix}-")
    ]
    by_name: dict[str, list[str]] = {}
    for node in members:
        by_name.setdefault(_norm(node.name), []).append(node.id)

    report = FamilyReport()
    mapped: list[GameNode] = []
    taken: set[str] = set()
    for entry in entries:
        index = entry["index"]
        if not entry.get("name"):
            report.unmatched.append(f"#{index}: the game has no name for it")
            continue
        title = clean(entry["name"])
        name = title
        if family.label is not None:
            numbered = _NUMBERED.fullmatch(title)
            if numbered is None or int(numbered["number"]) != index + 1:
                report.unmatched.append(f"#{index} {title!r}: does not read as #{index + 1}")
                continue
            title = numbered["title"]
            name = f"{family.label} {index + 1} ({title})"

        namesakes = by_name.get(_norm(title), [])
        if family.by_index:
            node_id = f"{family.id_prefix}-{index + 1}"
            existing = nodes.get(node_id)
            if existing is not None and family.label is None and not _same_name(
                existing.name, title
            ):
                report.unmatched.append(
                    f"#{index} {title!r}: {node_id} is {existing.name!r}"
                )
                continue
        elif len(namesakes) > 1:
            report.unmatched.append(f"#{index} {title!r}: names {', '.join(namesakes)}")
            continue
        elif namesakes:
            node_id = namesakes[0]
            existing = nodes[node_id]
        else:
            node_id = f"{family.id_prefix}-{slugify(title)}"
            existing = None

        if node_id in taken:
            report.unmatched.append(f"#{index} {title!r}: {node_id} is already mapped")
            continue
        if existing is None:
            if family.add_as is None:
                report.unmatched.append(f"#{index} {title!r}: no node")
                continue
            if node_id in nodes or any(i != node_id for i in namesakes):
                clash = node_id if node_id in nodes else namesakes[0]
                report.unmatched.append(f"#{index} {title!r}: clashes with {clash}")
                continue
            report.added += 1
        else:
            report.matched += 1
            if family.label is None and _norm(existing.name) != _norm(title):
                report.renamed.append(f"{node_id}: {existing.name!r} -> {title!r}")

        taken.add(node_id)
        desc = entry.get("desc")
        mapped.append(
            GameNode(
                id=node_id,
                name=name,
                description=readable(desc) if desc else None,
                system=family.system if existing is None else None,
                kind=family.add_as if existing is None else None,
            )
        )
    return mapped, report


def map_catalog(
    families: Mapping[str, Iterable[Mapping[str, Any]]],
    nodes: Iterable[Node],
    buildid: str | None,
) -> tuple[GameData, dict[str, FamilyReport], list[str]]:
    """Return the game file, a report per mapped family, and the skipped families."""
    by_id = {n.id: n for n in nodes}
    game = GameData(buildid=buildid)
    reports: dict[str, FamilyReport] = {}
    for prefix, family in FAMILIES.items():
        if prefix not in families:
            continue
        mapped, reports[prefix] = _map_family(family, families[prefix], by_id)
        game.nodes.extend(mapped)
    # Achievements key their rewards apart from the name and description pair,
    # so map_achievements reads them from the strings instead.
    skipped = [
        prefix for prefix in families if prefix not in FAMILIES and prefix != ACHIEVEMENT_PREFIX
    ]
    return game, reports, skipped


def grade_thresholds(wikitext: str) -> dict[str, list[str]]:
    """The wiki's Grade Bonuses thresholds, per grade, in table order."""
    start = wikitext.find("=== Grade Bonuses ===")
    if start < 0:
        return {}
    end = wikitext.find("\n===", start + 1)
    thresholds: dict[str, list[str]] = {}
    grade: str | None = None
    for row in wikitext[start : end if end >= 0 else None].split("|-"):
        first = next((line.strip() for line in row.splitlines() if line.strip()), "")
        header = _GRADE_HEADER.fullmatch(first)
        if header is not None:
            grade = header["grade"].lower()
            thresholds[grade] = []
        elif grade is not None and first[1:].strip().isdigit():
            thresholds[grade].append(first[1:].strip())
    return thresholds


def _place(
    node_id: str,
    name: str,
    description: str | None,
    system: str,
    kind: Kind,
    nodes: Mapping[str, Node],
    report: FamilyReport,
    effects: Iterable[str] = (),
) -> GameNode:
    existing = nodes.get(node_id)
    if existing is None:
        report.added += 1
    else:
        report.matched += 1
    return GameNode(
        id=node_id,
        name=name,
        description=description,
        effects=list(effects),
        system=system if existing is None else None,
        kind=kind if existing is None else None,
    )


def map_particles(
    strings: Mapping[str, str],
    nodes: Iterable[Node],
    thresholds: Mapping[str, list[str]],
) -> tuple[list[GameNode], dict[str, FamilyReport]]:
    """Map grade bonuses, Epsilon Tree effects and spark colours onto node ids.

    A grade bonus is named by its wiki threshold ("Rank 5 Bonus") only when the
    wiki lists exactly as many bonuses for that grade as the game has; a count
    that differs means the two lists cannot be paired by position, and the
    bonus is numbered instead ("Tetr Bonus #7").
    """
    by_id = {n.id: n for n in nodes}
    mapped: list[GameNode] = []
    reports: dict[str, FamilyReport] = {}

    bonuses: dict[str, dict[int, str]] = {}
    for key, text in strings.items():
        match = _GRADE_BONUS_KEY.fullmatch(key)
        if match is not None:
            bonuses.setdefault(match["grade"].lower(), {})[int(match["index"])] = text
    for grade in GRADES:
        if grade not in bonuses:
            continue
        report = reports[f"PARTICLES_BONUS_{grade.upper()}"] = FamilyReport()
        entries = sorted(bonuses[grade].items())
        wiki = thresholds.get(grade, [])
        aligned = len(wiki) == len(entries)
        for position, (index, text) in enumerate(entries):
            label = grade.capitalize()
            name = (
                f"{label} {wiki[position]} Bonus" if aligned else f"{label} Bonus #{index + 1}"
            )
            mapped.append(_place(
                f"{grade_bonus_prefix(grade)}{index + 1}",
                name,
                readable(text, formulas=True),
                GRADE_SYSTEM,
                Kind.UPGRADE,
                by_id,
                report,
            ))

    effects = sorted(
        (int(m["index"]), text)
        for key, text in strings.items()
        if (m := _EPSILON_EFFECT_KEY.fullmatch(key)) is not None
    )
    if effects:
        report = reports["EPSILON_EFFECT"] = FamilyReport()
        for index, text in effects:
            if index not in _OUTER_EFFECTS:
                report.unmatched.append(
                    f"#{index}: not a known outer node (A1-A16 are #15-#30)"
                )
                continue
            label = index - _OUTER_EFFECTS.start + 1
            effect = clean(text)
            mapped.append(_place(
                f"epsilon-tree-a{label}",
                f"Epsilon Tree A{label} ({effect})",
                effect,
                EPSILON_TREE_SYSTEM,
                Kind.TREE_NODE,
                by_id,
                report,
            ))

    colours = sorted(
        (m["colour"], text)
        for key, text in strings.items()
        if (m := _SPARK_EFFECT_KEY.fullmatch(key)) is not None
    )
    if colours:
        report = reports["ENUM_SPARKTYPE"] = FamilyReport()
        for colour, text in colours:
            title = clean(strings.get(f"ENUM_SPARKTYPE_{colour}", colour.capitalize()))
            name_template = strings.get(_SPARK_NAME)
            mapped.append(_place(
                f"particles-spark-{colour.lower()}",
                name_template.replace("{0}", title) if name_template else title,
                readable(text),
                SPARK_SYSTEM,
                Kind.UPGRADE,
                by_id,
                report,
            ))
    return mapped, reports


def wiki_achievements(wikitext: str) -> dict[str, dict[str, str]]:
    """The wiki's Achievements rows by normalised name; a name used twice is dropped."""
    rows: dict[str, dict[str, str]] = {}
    repeated: set[str] = set()
    for match in _WIKI_ACHIEVEMENT.finditer(wikitext):
        fields = template_fields(match["body"])
        key = _norm(fields.get("name", ""))
        if key in rows:
            repeated.add(key)
        rows[key] = fields
    return {key: row for key, row in rows.items() if key and key not in repeated}


def _filled(template: str, wiki: str | None) -> str:
    """Word a game string, taking the numbers it leaves to runtime from the wiki.

    An achievement's threshold is a constant the game still fills in at runtime
    ("Reach {0} Score"). When the wiki words the same achievement exactly as the
    game does around the number ("Reach 1,000,000 Score"), the number is taken
    from it; any other wording leaves the placeholder to `readable`.
    """
    text = clean(_RUNNING_TOTAL.sub("", template))
    parts = re.split(_PLACEHOLDER, text)
    if wiki and len(parts) > 1:
        match = re.fullmatch(
            _WIKI_AMOUNT.join(map(re.escape, parts)), " ".join(label_text(wiki).split())
        )
        if match is not None:
            text = "".join(
                part + value for part, value in zip(parts, (*match.groups(), ""), strict=True)
            )
    return readable(text)


def _wiki_row(title: str, wiki: Mapping[str, Mapping[str, str]]) -> Mapping[str, str]:
    exact = wiki.get(_norm(title))
    if exact is not None:
        return exact
    near = [row for key, row in wiki.items() if _same_name(key, title)]
    return near[0] if len(near) == 1 else {}


def map_achievements(
    strings: Mapping[str, str],
    nodes: Iterable[Node],
    wiki: Mapping[str, Mapping[str, str]],
) -> tuple[list[GameNode], FamilyReport]:
    """Map every achievement with a reward onto `achievement-<n>`.

    `n` counts from 1, the number the game's own text cites ("Changes the
    reward for Ach. 29" is `ACH_REWD_28_NEW`); secrets are
    `achievement-secret-<n>`. The requirement is the description and the
    reward the effect. `wiki` is `wiki_achievements` of the Achievements page,
    read only for the thresholds the game leaves to runtime. A row is paired
    by name, or by a near spelling when exactly one row has one ("Generators
    Power" / "Generator Power"); `_filled` still checks every other word.
    """
    by_id = {n.id: n for n in nodes}
    report = FamilyReport()
    mapped: list[GameNode] = []
    named = {
        int(m["index"]) for key in strings if (m := _ACHIEVEMENT_NAME_KEY.fullmatch(key))
    }
    rewarded = sorted(
        int(m["index"]) for key in strings if (m := _ACHIEVEMENT_REWARD_KEY.fullmatch(key))
    )
    report.left_out = len(named - set(rewarded))
    for index in rewarded:
        if index not in named:
            report.unmatched.append(f"#{index}: the game has no name for it")
            continue
        title = clean(strings[f"ACH_NAME_{index}"])
        if index < _SECRET_BASE:
            number = index + 1
            node_id, name = f"achievement-{number}", f"Achievement {number} ({title})"
            row = _wiki_row(title, wiki)
        else:
            number = index - _SECRET_BASE + 1
            node_id = f"achievement-secret-{number}"
            name = f"Secret Achievement {number} ({title})"
            row = {}
        requirement = strings.get(f"ACH_DESC_{index}")
        effects = [_filled(strings[f"ACH_REWD_{index}"], row.get("reward"))]
        swapped = strings.get(f"ACH_REWD_{index}_NEW")
        if swapped:
            effects.append(readable(swapped))
        mapped.append(_place(
            node_id,
            name,
            _filled(requirement, row.get("description")) if requirement else None,
            ACHIEVEMENT_SYSTEM,
            Kind.ACHIEVEMENT,
            by_id,
            report,
            effects,
        ))
    return mapped, report


# Index ranges below are the ones checked text-by-text against the wiki's
# effects for the node of the same number; an index outside is reported.
_REFINE_REWARD_KEY = re.compile(r"UNI_MIN_REF_NODE_REWARD_(?P<index>\d+)")
_REFINE_REWARDS = range(200)
_ELEMENT_EFFECT_KEY = re.compile(r"UNI_ELEM_TREE_NODE_EFFECT_(?P<element>[A-Z]+)_(?P<index>\d+)")
_ELEMENT_EFFECTS = {"FIRE": range(11), "WATER": range(11), "WIND": range(12), "EARTH": range(10)}
_ETERNITY_CHALLENGE_KEY = re.compile(r"ETR_CHA_REWD_(?P<index>\d+)")
_ETERNITY_CHALLENGES = range(10)
_INFINITY_UPGRADE_KEY = re.compile(r"INF_UPGRADE_NAME_(?P<row>\d+)_(?P<col>\d+)")
# The wiki prefixes each infinity upgrade with its grid cell: "6;1 Mighty Ascend".
_GRID_CELL = re.compile(r"\d+;\d+\s+")
_ANIMAL_KEY = re.compile(r"ETR_ANL_NAME_(?P<row>\d+)_(?P<col>\d+)")
_SING_MILESTONE_KEY = re.compile(
    r"SING_MILESTONES_NAME_(?P<track>SING|ATOM|PROG)_(?P<index>\d+)"
)
_SING_MILESTONE_SYSTEMS = {
    "SING": "singularity-milestones-singularity",
    "ATOM": "singularity-milestones-atoms",
    "PROG": "singularity-milestones-progression",
}
_TAROT_CARD_KEY = re.compile(r"UNI_TAROT_CARD_(?P<suit>ARCAN|CUP|PENTACLE|SWORD|WAND)_(?P<index>\d+)")
_ARTIFACT_PART_KEY = re.compile(r"TAROT_ARTIFACT_PART_NAME_(?P<suit>[A-Z]+)_(?P<index>\d+)")
_TAROT_UPGRADE_KEY = re.compile(r"UNI_TAROT_UPGRADE_EFFECT_(?P<suit>[A-Z]+)_(?P<index>\d+)")
# The Eternities each milestone needs, read off the game's Eternity >
# Milestones screen: REWD_<k> is milestone k+1. The wiki numbers its nodes by
# this count, so REWD_3 (5 Eternities) is eternity-milestone-5.
_ETERNITY_MILESTONE_KEY = re.compile(r"ETR_MIL_REWD_(?P<index>\d+)")
_ETERNITY_MILESTONE_THRESHOLDS = (1, 2, 3, 5, 7, 8, 12, 14, 16, 32, 100)


def _matches(
    strings: Mapping[str, str], pattern: re.Pattern[str]
) -> list[tuple[re.Match[str], str]]:
    found = [(m, text) for key, text in strings.items() if (m := pattern.fullmatch(key))]
    # Numerically, so the game file lists node 2 before node 10.
    return sorted(
        found,
        key=lambda pair: tuple(int(g) if g.isdigit() else g for g in pair[0].groups()),
    )


# Every Arcana card's second effect; it says nothing about the card.
_COOLDOWN = re.compile(rf"Cooldown Time:\s*{_PLACEHOLDER}")


def _join(parts: Iterable[str]) -> str | None:
    """Sentences as they are, fragments separated by "; "."""
    text = ""
    for part in parts:
        if text:
            text += " " if text[-1] in ".!?" else "; "
        text += part
    return text or None


def _namesake(
    title: str, members: list[Node], report: FamilyReport, label: str
) -> str | None:
    """The one member named `title`, exactly or else as a near spelling."""
    for same in (lambda n: _norm(n.name) == _norm(title), lambda n: _same_name(n.name, title)):
        found = [n.id for n in members if same(n)]
        if len(found) == 1:
            return found[0]
        if found:
            report.unmatched.append(f"{label} {title!r}: names {', '.join(found)}")
            return None
    report.unmatched.append(f"{label} {title!r}: no node of that name")
    return None


def map_strings(
    strings: Mapping[str, str], nodes: Iterable[Node]
) -> tuple[list[GameNode], dict[str, FamilyReport]]:
    """Map the game's keyed texts outside the _NAME_/_DESC_ pairs onto nodes.

    Each entity matches a node by an index checked against the wiki's effects,
    by the number in its name, or by its name. Only eternity milestones, whose
    thresholds were read off the game screen, may create a node; every other
    entity without one is reported. A name is written only where the game
    gives one, so a description-only entry leaves the node's name alone.
    """
    by_id = {n.id: n for n in nodes}
    mapped: list[GameNode] = []
    reports: dict[str, FamilyReport] = {}
    taken: set[str] = set()

    def members(system: str, prefix: str) -> list[Node]:
        return [n for n in by_id.values() if n.system == system and n.id.startswith(prefix)]

    def report_for(family: str) -> FamilyReport:
        return reports.setdefault(family, FamilyReport())

    def claim(node_id: str, report: FamilyReport, label: str) -> bool:
        if node_id in taken:
            report.unmatched.append(f"{label}: {node_id} is already mapped")
            return False
        taken.add(node_id)
        return True

    def overlay(
        node_id: str,
        name: str | None,
        description: str | None,
        report: FamilyReport,
        label: str,
    ) -> None:
        node = by_id.get(node_id)
        if node is None:
            report.unmatched.append(f"{label}: no node {node_id}")
            return
        if not claim(node_id, report, label):
            return
        report.matched += 1
        if name is not None and _norm(name) != _norm(node.name):
            report.renamed.append(f"{node_id}: {node.name!r} -> {name!r}")
        mapped.append(GameNode(id=node_id, name=name, description=description))

    for m, text in _matches(strings, _REFINE_REWARD_KEY):
        report, index = report_for("UNI_MIN_REF_NODE_REWARD"), int(m["index"])
        if index not in _REFINE_REWARDS:
            report.unmatched.append(f"#{index}: beyond the checked #0-#{_REFINE_REWARDS.stop - 1}")
            continue
        overlay(f"refine-node-{index + 1}", None, readable(text), report, f"#{index}")

    for m, text in _matches(strings, _ELEMENT_EFFECT_KEY):
        element, index = m["element"], int(m["index"])
        report = report_for("UNI_ELEM_TREE_NODE_EFFECT")
        if index not in _ELEMENT_EFFECTS.get(element, range(0)):
            report.unmatched.append(f"{element} #{index}: not a checked node")
            continue
        overlay(
            f"{element.lower()}-node-{index + 1}", None, readable(text), report,
            f"{element} #{index}",
        )

    for m, text in _matches(strings, _ETERNITY_CHALLENGE_KEY):
        report, index = report_for("ETR_CHA"), int(m["index"])
        title = clean(strings.get(f"ETR_CHL_NAME_{index}", ""))
        numbered = _NUMBERED.fullmatch(title)
        if index not in _ETERNITY_CHALLENGES or numbered is None or int(numbered["number"]) != index + 1:
            report.unmatched.append(f"#{index} {title!r}: not a checked challenge")
            continue
        overlay(
            f"eternity-challenge-{index + 1}",
            f"Eternity Challenge {index + 1} ({numbered['title']})",
            readable(text), report, f"#{index}",
        )

    for m, text in _matches(strings, _ETERNITY_MILESTONE_KEY):
        report, index = report_for("ETR_MIL"), int(m["index"])
        if index >= len(_ETERNITY_MILESTONE_THRESHOLDS):
            report.unmatched.append(f"#{index}: no threshold checked in the game")
            continue
        count = _ETERNITY_MILESTONE_THRESHOLDS[index]
        node_id = f"eternity-milestone-{count}"
        if claim(node_id, report, f"#{index}"):
            mapped.append(_place(
                node_id,
                f"Eternity Milestone ({count} {'Eternity' if count == 1 else 'Eternities'})",
                readable(text),
                "eternity-milestones",
                Kind.UPGRADE,
                by_id,
                report,
            ))

    for m, title in _matches(strings, _INFINITY_UPGRADE_KEY):
        row, col = m["row"], m["col"]
        report, title = report_for("INF_UPGRADE"), clean(title)
        cell = [n for n in by_id.values() if n.id.startswith(f"infinity-upgrade-{row}-{col}-")]
        if len(cell) != 1 or not _same_name(_GRID_CELL.sub("", cell[0].name, count=1), title):
            found = ", ".join(n.id for n in cell) or "no node"
            report.unmatched.append(f"{row};{col} {title!r}: {found}")
            continue
        desc = strings.get(f"INF_UPGRADE_REWD_{row}_{col}")
        overlay(
            cell[0].id, f"{row};{col} {title}", readable(desc) if desc else None,
            report, f"{row};{col}",
        )

    named = (
        ("ETR_ANL", _ANIMAL_KEY, lambda m: ("animals", "animal-"),
         lambda m: f"ETR_ANL_REWD_{m['row']}_{m['col']}"),
        ("SING_MILESTONES", _SING_MILESTONE_KEY,
         lambda m: (_SING_MILESTONE_SYSTEMS[m["track"]], "singularity-milestone-"),
         lambda m: f"SING_MILESTONES_REWD_{m['track']}_{m['index']}"),
        ("TAROT_ARTIFACT_PART", _ARTIFACT_PART_KEY, lambda m: ("tarot-artifacts", "tarot-artifact-"),
         lambda m: f"TAROT_ARTIFACT_PART_{m['index']}_EFFECT_{m['suit']}"),
    )
    for family, pattern, home, desc_key in named:
        for m, title in _matches(strings, pattern):
            report, title = report_for(family), clean(title)
            node_id = _namesake(title, members(*home(m)), report, m.string)
            if node_id is not None:
                desc = strings.get(desc_key(m))
                overlay(node_id, title, readable(desc) if desc else None, report, m.string)

    for m, title in _matches(strings, _TAROT_CARD_KEY):
        suit, index = m["suit"], m["index"]
        report, title = report_for("UNI_TAROT_CARD"), clean(title)
        node_id = _namesake(title, members("tarot", "tarot-"), report, m.string)
        if node_id is None:
            continue
        effects = [
            readable(effect)
            for n in (1, 2)
            if (effect := strings.get(f"UNI_TAROT_CARD_EFFECT_{n}_{suit}_{index}")) is not None
            and not _COOLDOWN.fullmatch(effect)
        ]
        overlay(node_id, title, _join(effects), report, m.string)
        reward = strings.get(f"UNI_TAROT_CARD_{suit}_REWARD_{index}")
        if reward is not None:
            overlay(
                f"tarot-challenge-{slugify(title)}", None, f"Reward: {readable(reward)}",
                report_for("UNI_TAROT_CARD_REWARD"), m.string,
            )

    for m, _ in _matches(strings, _TAROT_UPGRADE_KEY):
        report_for("UNI_TAROT_UPGRADE_EFFECT").unmatched.append(
            f"{m.string}: no node models a single tarot upgrade"
        )
    return mapped, reports


def to_yaml(game: GameData) -> str:
    doc = {
        "buildid": game.buildid,
        "nodes": [n.model_dump(mode="json", exclude_defaults=True) for n in game.nodes],
    }
    return GAME_FILE_HEADER + yaml.safe_dump(
        doc, sort_keys=False, allow_unicode=True, width=1_000_000
    )
