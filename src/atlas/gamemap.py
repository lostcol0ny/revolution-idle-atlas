"""Map the game's catalog families onto graph node ids, for data/game.yaml.

`atlas game` runs this against the wiki-derived dataset and commits the
result; `atlas build` only reads it, so CI rebuilds the graph without a game.
Only families with a clear home in the graph are mapped. An entity that cannot
be placed is reported, never guessed at.
"""

