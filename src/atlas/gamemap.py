_GRADE_HEADER = re.compile(r"!.*\|\s*(?P<grade>Rank|Tier|Tetr|Pent) Bonuses")


@dataclass
class FamilyReport:
    matched: int = 0
    added: int = 0
    unmatched: list[str] = field(default_factory=list)
    # A match whose game name differs from the node's current name.
    renamed: list[str] = field(default_factory=list)


def clean(text: str) -> str:
    """Drop Unity rich-text tags and collapse whitespace."""
    return " ".join(_TAG.sub("", _LINE_BREAK.sub(" ", text)).split())


def readable(text: str, *, formulas: bool = False) -> str:
    """Clean a description and word its runtime placeholders.

    The game fills `{0}` in at runtime, so a bare token tells a reader
    nothing; the symbol beside it says what sort of number it is. `formulas`
    typesets the arithmetic a description spells out in plain text (see
    `typeset`); without it the whole text stays prose.
    """
    text = _CURRENT_STATE.sub("", _RUNNING_TOTAL.sub("", clean(text)))
    for pattern, phrase in _PHRASES:
        text = pattern.sub(phrase, text)
    # Same text format as wiki prose: `$` would otherwise open inline math.
    return typeset(text) if formulas else escape_prose(text)


# The grade bonuses write their formulas in plain text: "×(1 + 0.05 × rank)",
# "(gain × 100)^(1 + 0.1 × pent) / 100". A grade is an operand anywhere. The
# other words are operands only inside parentheses, because outside them they
# are the prose a formula sits in: "Attack gold gain ^(1 + 0.01 × tetr)".
_FORMULA_TOKEN = re.compile(
    r"\s*(?:"
    r"(?P<func>(?i:sqrt))(?=\()"
    r"|(?<![\w.])(?P<grade>(?i:rank|tier|tetr|pent))(?!\w)"
    r"|(?<![\w.])(?P<word>equipped ER level|generator level|multiplier level|gain|[αβγδ])(?!\w)"
    r"|(?<![\w.])(?P<num>\d+(?:\.\d+)?)(?!\w)"
    r"|(?P<op>[×+\-/^]|(?<=\s)x(?=\s))"
    r"|(?P<open>\()|(?P<close>\))"
    r")"
)
_OPERAND_START = frozenset({"func", "grade", "word", "num", "open"})
_OPERAND_END = frozenset({"grade", "word", "num", "close"})
# Operators that may open a formula: "×(1 + 0.1 × tier)", "^(1 + 0.2 × tetr)",
# "speed + 0.01 x Sqrt(rank)". The formula is what the prose before it gets.
_LEADING_OPS = frozenset("×^+")


@dataclass(frozen=True)
class _Token:
    kind: str
    text: str
    start: int
    end: int


def _formula_runs(text: str) -> list[list[_Token]]:
    """Maximal runs of formula tokens, split where two operands meet."""
    runs: list[list[_Token]] = []
    run: list[_Token] = []
    depth = 0
    pos = 0
    while pos < len(text):
        match = _FORMULA_TOKEN.match(text, pos)
        kind = match.lastgroup if match else None
        if kind == "word" and depth == 0:
            kind = None
        # "x" is a letter unless it stands between two operands.
        if kind == "op" and match and match["op"] == "x" and (
            not run or run[-1].kind not in _OPERAND_END
        ):
            kind = None
        if kind is None or match is None:
            if run:
                runs.append(run)
            run, depth = [], 0
            pos += 1
            continue
        if kind in _OPERAND_START and run and run[-1].kind in _OPERAND_END:
            # "tetr 10", "^0.2 (improved by ...)": no operator, so two runs.
            runs.append(run)
            run, depth = [], 0
            continue
        depth += {"open": 1, "close": -1}.get(kind, 0)
        run.append(_Token(kind, match[kind], match.start(kind), match.end(kind)))
        pos = match.end()
    if run:
        runs.append(run)
    return runs


def _trim(run: list[_Token]) -> list[_Token]:
    """Drop the edges of a run that cannot belong to its formula."""
    run = list(run)
    while run:
        opens = sum(t.kind == "open" for t in run)
        closes = sum(t.kind == "close" for t in run)
        first, last = run[0], run[-1]
        if (
            first.kind == "close"
            or (first.kind == "op" and first.text not in _LEADING_OPS)
            or (first.kind == "open" and opens > closes)
        ):
            run.pop(0)
        elif last.kind in ("open", "op", "func") or (last.kind == "close" and closes > opens):
            run.pop()
        else:
            break
    return run


def _is_formula(run: list[_Token]) -> bool:
    """True for well-formed arithmetic with at least one binary operator.

    A lone leading operator is the game's shorthand ("^1.1", "×tier",
    "+0.01 per rank") and stays prose.
    """
    depth = 0
    binary = False
    for i, token in enumerate(run):
        depth += {"open": 1, "close": -1}.get(token.kind, 0)
        if depth < 0:
            return False
        following = run[i + 1].kind if i + 1 < len(run) else None
        if token.kind == "func":
            if following != "open":
                return False
            binary = True
        elif token.kind == "op":
            if following not in _OPERAND_START:
                return False
            if i > 0:
                if run[i - 1].kind not in _OPERAND_END:
                    return False
                binary = True
    return depth == 0 and binary


def _operand_end(run: list[_Token], start: int) -> int:
    """The index just past the operand that begins at `start`."""
    end = start + 1 if run[start].kind == "func" else start
    if run[end].kind != "open":
        return end + 1
    depth = 0
    for i in range(end, len(run)):
        depth += {"open": 1, "close": -1}.get(run[i].kind, 0)
        if depth == 0:
            return i + 1
    raise AssertionError("unbalanced run passed _is_formula")


def _latex(run: list[_Token]) -> str:
    parts: list[str] = []
    i = 0
    while i < len(run):
        token = run[i]
        if token.kind == "func":
            end = _operand_end(run, i)
            parts.append(rf"\sqrt{{{_latex(run[i + 2 : end - 1])}}}")
            i = end
            continue
        if token.text == "^":
            end = _operand_end(run, i + 1)
            operand = run[i + 1 : end]
            # The braces group the exponent, so its parentheses are redundant.
            if operand[0].kind == "open":
                operand = operand[1:-1]
            parts.append(f"^{{{_latex(operand)}}}")
            i = end
            continue
        if token.kind in ("grade", "word") and token.text.isascii():
            parts.append(rf"\text{{{token.text}}}")
        elif token.text in ("×", "x"):
            parts.append(r"\times")
        else:
            parts.append(token.text)
        i += 1
    return " ".join(parts).replace("( ", "(").replace(" )", ")").replace(" ^{", "^{")


def typeset(text: str) -> str:
    """Escape prose, and turn the formulas in it into `$LaTeX$`.

    Conservative on purpose: only a balanced run of numbers, grades, a few
    known operand words and operators, with a binary operator in it, becomes
    math. Anything else stays prose exactly as the game wrote it.
    """
    out: list[str] = []
    pos = 0
    for raw in _formula_runs(text):
        run = _trim(raw)
        if not _is_formula(run):
            continue
        start, end = run[0].start, run[-1].end
        out += [escape_prose(text[pos:start]), f"${_latex(run)}$"]
        pos = end
    out.append(escape_prose(text[pos:]))
    return "".join(out)


def _norm(name: str) -> str:
    return _NON_ALNUM.sub("", name.casefold())


def _same_name(a: str, b: str) -> bool:
    return SequenceMatcher(None, _norm(a), _norm(b)).ratio() >= SAME_NAME_RATIO


def _map_family(
    family: Family, entries: Iterable[Mapping[str, Any]], nodes: Mapping[str, Node]
) -> tuple[list[GameNode], FamilyReport]:
    members = [
        n
        for n in nodes.values()
        if n.system == family.system and n.id.startswith(f"{family.id_prefix}-")
    ]
    by_name: dict[str, list[str]] = {}
    for node in members:
        by_name.setdefault(_norm(node.name), []).append(node.id)

    report = FamilyReport()
    mapped: list[GameNode] = []
    taken: set[str] = set()
    for entry in entries:
        index = entry["index"]
        if not entry.get("name"):
            report.unmatched.append(f"#{index}: the game has no name for it")
            continue
        title = clean(entry["name"])
        name = title
        if family.label is not None:
            numbered = _NUMBERED.fullmatch(title)
            if numbered is None or int(numbered["number"]) != index + 1:
                report.unmatched.append(f"#{index} {title!r}: does not read as #{index + 1}")
                continue
            title = numbered["title"]
            name = f"{family.label} {index + 1} ({title})"

        namesakes = by_name.get(_norm(title), [])
        if family.by_index:
            node_id = f"{family.id_prefix}-{index + 1}"
            existing = nodes.get(node_id)
            if existing is not None and family.label is None and not _same_name(
                existing.name, title
            ):
                report.unmatched.append(
                    f"#{index} {title!r}: {node_id} is {existing.name!r}"
                )
                continue
        elif len(namesakes) > 1:
            report.unmatched.append(f"#{index} {title!r}: names {', '.join(namesakes)}")
            continue
        elif namesakes:
            node_id = namesakes[0]
            existing = nodes[node_id]
        else:
            node_id = f"{family.id_prefix}-{slugify(title)}"
            existing = None

        if node_id in taken:
            report.unmatched.append(f"#{index} {title!r}: {node_id} is already mapped")
            continue
        if existing is None:
            if family.add_as is None:
                report.unmatched.append(f"#{index} {title!r}: no node")
                continue
            if node_id in nodes or any(i != node_id for i in namesakes):
                clash = node_id if node_id in nodes else namesakes[0]
                report.unmatched.append(f"#{index} {title!r}: clashes with {clash}")
                continue
            report.added += 1
        else:
            report.matched += 1
            if family.label is None and _norm(existing.name) != _norm(title):
                report.renamed.append(f"{node_id}: {existing.name!r} -> {title!r}")

        taken.add(node_id)
        desc = entry.get("desc")
        mapped.append(
            GameNode(
                id=node_id,
                name=name,
                description=readable(desc) if desc else None,
                system=family.system if existing is None else None,
                kind=family.add_as if existing is None else None,
            )
        )
    return mapped, report


def map_catalog(
    families: Mapping[str, Iterable[Mapping[str, Any]]],
    nodes: Iterable[Node],
    buildid: str | None,
) -> tuple[GameData, dict[str, FamilyReport], list[str]]:
    """Return the game file, a report per mapped family, and the skipped families."""
    by_id = {n.id: n for n in nodes}
    game = GameData(buildid=buildid)
    reports: dict[str, FamilyReport] = {}
    for prefix, family in FAMILIES.items():
        if prefix not in families:
            continue
        mapped, reports[prefix] = _map_family(family, families[prefix], by_id)
        game.nodes.extend(mapped)
    skipped = [prefix for prefix in families if prefix not in FAMILIES]
    return game, reports, skipped


def grade_thresholds(wikitext: str) -> dict[str, list[str]]:
    """The wiki's Grade Bonuses thresholds, per grade, in table order."""
    start = wikitext.find("=== Grade Bonuses ===")
    if start < 0:
        return {}
    end = wikitext.find("\n===", start + 1)
    thresholds: dict[str, list[str]] = {}
    grade: str | None = None
    for row in wikitext[start : end if end >= 0 else None].split("|-"):
        first = next((line.strip() for line in row.splitlines() if line.strip()), "")
        header = _GRADE_HEADER.fullmatch(first)
        if header is not None:
            grade = header["grade"].lower()
            thresholds[grade] = []
        elif grade is not None and first[1:].strip().isdigit():
            thresholds[grade].append(first[1:].strip())
    return thresholds


def _place(
    node_id: str,
    name: str,
    description: str | None,
    system: str,
    kind: Kind,
    nodes: Mapping[str, Node],
    report: FamilyReport,
) -> GameNode:
    existing = nodes.get(node_id)
    if existing is None:
        report.added += 1
    else:
        report.matched += 1
    return GameNode(
        id=node_id,
        name=name,
        description=description,
        system=system if existing is None else None,
        kind=kind if existing is None else None,
    )


def map_particles(
    strings: Mapping[str, str],
    nodes: Iterable[Node],
    thresholds: Mapping[str, list[str]],
) -> tuple[list[GameNode], dict[str, FamilyReport]]:
    """Map grade bonuses, Epsilon Tree effects and spark colours onto node ids.

    A grade bonus is named by its wiki threshold ("Rank 5 Bonus") only when the
    wiki lists exactly as many bonuses for that grade as the game has; a count
    that differs means the two lists cannot be paired by position, and the
    bonus is numbered instead ("Tetr Bonus #7").
    """
    by_id = {n.id: n for n in nodes}
    mapped: list[GameNode] = []
    reports: dict[str, FamilyReport] = {}

    bonuses: dict[str, dict[int, str]] = {}
    for key, text in strings.items():
        match = _GRADE_BONUS_KEY.fullmatch(key)
        if match is not None:
            bonuses.setdefault(match["grade"].lower(), {})[int(match["index"])] = text
    for grade in GRADES:
        if grade not in bonuses:
            continue
        report = reports[f"PARTICLES_BONUS_{grade.upper()}"] = FamilyReport()
        entries = sorted(bonuses[grade].items())
        wiki = thresholds.get(grade, [])
        aligned = len(wiki) == len(entries)
        for position, (index, text) in enumerate(entries):
            label = grade.capitalize()
            name = (
                f"{label} {wiki[position]} Bonus" if aligned else f"{label} Bonus #{index + 1}"
            )
            mapped.append(_place(
                f"{grade_bonus_prefix(grade)}{index + 1}",
                name,
                readable(text, formulas=True),
                GRADE_SYSTEM,
                Kind.UPGRADE,
                by_id,
                report,
            ))

    effects = sorted(
        (int(m["index"]), text)
        for key, text in strings.items()
        if (m := _EPSILON_EFFECT_KEY.fullmatch(key)) is not None
    )
    if effects:
        report = reports["EPSILON_EFFECT"] = FamilyReport()
        for index, text in effects:
            if index not in _OUTER_EFFECTS:
                report.unmatched.append(
                    f"#{index}: not a known outer node (A1-A16 are #15-#30)"
                )
                continue
            label = index - _OUTER_EFFECTS.start + 1
            effect = clean(text)
            mapped.append(_place(
                f"epsilon-tree-a{label}",
                f"Epsilon Tree A{label} ({effect})",
                effect,
                EPSILON_TREE_SYSTEM,
                Kind.TREE_NODE,
                by_id,
                report,
            ))

    colours = sorted(
        (m["colour"], text)
        for key, text in strings.items()
        if (m := _SPARK_EFFECT_KEY.fullmatch(key)) is not None
    )
    if colours:
        report = reports["ENUM_SPARKTYPE"] = FamilyReport()
        for colour, text in colours:
            title = clean(strings.get(f"ENUM_SPARKTYPE_{colour}", colour.capitalize()))
            name_template = strings.get(_SPARK_NAME)
            mapped.append(_place(
                f"particles-spark-{colour.lower()}",
                name_template.replace("{0}", title) if name_template else title,
                readable(text),
                SPARK_SYSTEM,
                Kind.UPGRADE,
                by_id,
                report,
            ))
    return mapped, reports


