"""Map the game's catalog families onto graph node ids, for data/game.yaml.

`atlas game` runs this against the wiki-derived dataset and commits the
result; `atlas build` only reads it, so CI rebuilds the graph without a game.
Only families with a clear home in the graph are mapped. An entity that cannot
be placed is reported, never guessed at.
"""

import re
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from difflib import SequenceMatcher
from pathlib import Path
from typing import Any

import yaml

from atlas.extract.refs import slugify
from atlas.models import GameData, GameNode, Kind, Node

GAME_FILE_REL_PATH = Path("data", "game.yaml")

GAME_FILE_HEADER = (
    "# Generated by `atlas game` from a local game install, and committed.\n"
    "# `atlas build` overlays it on data/derived.yaml; data/relationships.yaml\n"
    "# still wins every field. Do not hand-edit: the next run overwrites it.\n"
)

# Unity rich text: <color=#fff>, </color>, <sprite name=x>, <pos=5%>, <s>. Only
# a tag-shaped run is dropped, so prose such as "<==" survives.
_TAG = re.compile(r"</?[A-Za-z][\w-]*(?:[= ][^<>]*)?>")
_LINE_BREAK = re.compile(r"<br\s*/?>", re.IGNORECASE)
_PLACEHOLDER = r"\{\d+(?::[^{}]*)?\}"
# A running total such as "(total: x{1})" is the player's state, not a
# description of the entity, so it goes rather than being reworded.
_RUNNING_TOTAL = re.compile(rf"\s*\((?:[^():]*:\s*)?[x+^-]?{_PLACEHOLDER}%?\)")
# Most specific shape first: "x{0}%" is still a multiplier, "+{0}%" a percentage.
_PHRASES = (
    (re.compile(rf"(?<![A-Za-z])x{_PLACEHOLDER}%?"), "a multiplier"),
    (re.compile(rf"\^{_PLACEHOLDER}"), "an exponent"),
    (re.compile(rf"[+-]?{_PLACEHOLDER}%"), "a percentage"),
    (re.compile(rf"[+-]{_PLACEHOLDER}"), "an amount"),
    (re.compile(_PLACEHOLDER), "a value"),
)
# "#1 Ionized Speed", or "#1 IP Gain ({0})" where the game appends the level.
_NUMBERED = re.compile(r"#(?P<number>\d+)\s+(?P<title>.+?)(?:\s*\(\{\d+\}\))?")
_NON_ALNUM = re.compile(r"[^0-9a-z]")
# The wiki and the game spell some names differently ("Magestic Halberd" /
# "Majestic Halberd", "Lucky Luck Crystal" / "Lucky Crystal"); an index that
# has slipped pairs unrelated names, which score far below this.
SAME_NAME_RATIO = 0.8


@dataclass(frozen=True)
class Family:
    system: str
    id_prefix: str
    # True: entity n is `<id_prefix>-<n+1>`, as relics and challenges are
    # numbered. False: matched by name among the system's `<id_prefix>-*` nodes.
    by_index: bool
    # The kind to create a node with when no node matches; None never creates.
    add_as: Kind | None
    # For names the game writes as "#<n> Title": the display name becomes
    # "<label> <n> (Title)", and the number, not the title, verifies the index.
    label: str | None = None


FAMILIES: dict[str, Family] = {
    "UNI_RELIC": Family("relics", "relic", by_index=True, add_as=Kind.RELIC),
    "INF_CHL": Family(
        "infinity-challenges",
        "infinity-challenge",
        by_index=True,
        add_as=Kind.UPGRADE,
        label="Infinity Challenge",
    ),
    "ETR_RP_UPGRADE": Family(
        "laboratory", "rp-upgrade", by_index=True, add_as=Kind.UPGRADE, label="RP Upgrade"
    ),
    "PLAGUE_ENDO_UPGRADE": Family(
        "plague", "plague-er", by_index=False, add_as=Kind.UPGRADE
    ),
    # The hundred common mineral tiers. No node models a single tier, and a
    # hundred edgeless nodes would bury the minerals system, so they are only
    # matched, never created.
    "UNI_MIN_COMMON": Family("minerals", "mineral", by_index=False, add_as=None),
}


@dataclass
class FamilyReport:
    matched: int = 0
    added: int = 0
    unmatched: list[str] = field(default_factory=list)
    # A match whose game name differs from the node's current name.
    renamed: list[str] = field(default_factory=list)


def clean(text: str) -> str:
    """Drop Unity rich-text tags and collapse whitespace."""
    return " ".join(_TAG.sub("", _LINE_BREAK.sub(" ", text)).split())


def readable(text: str) -> str:
    """Clean a description and word its runtime placeholders.

    The game fills `{0}` in at runtime, so a bare token tells a reader
    nothing; the symbol beside it says what sort of number it is.
    """
    text = _RUNNING_TOTAL.sub("", clean(text))
    for pattern, phrase in _PHRASES:
        text = pattern.sub(phrase, text)
    return text


def _norm(name: str) -> str:
    return _NON_ALNUM.sub("", name.casefold())


def _same_name(a: str, b: str) -> bool:
    return SequenceMatcher(None, _norm(a), _norm(b)).ratio() >= SAME_NAME_RATIO


def _map_family(
    family: Family, entries: Iterable[Mapping[str, Any]], nodes: Mapping[str, Node]
) -> tuple[list[GameNode], FamilyReport]:
    members = [
        n
        for n in nodes.values()
        if n.system == family.system and n.id.startswith(f"{family.id_prefix}-")
    ]
    by_name: dict[str, list[str]] = {}
    for node in members:
        by_name.setdefault(_norm(node.name), []).append(node.id)

    report = FamilyReport()
    mapped: list[GameNode] = []
    taken: set[str] = set()
    for entry in entries:
        index = entry["index"]
        if not entry.get("name"):
            report.unmatched.append(f"#{index}: the game has no name for it")
            continue
        title = clean(entry["name"])
        name = title
        if family.label is not None:
            numbered = _NUMBERED.fullmatch(title)
            if numbered is None or int(numbered["number"]) != index + 1:
                report.unmatched.append(f"#{index} {title!r}: does not read as #{index + 1}")
                continue
            title = numbered["title"]
            name = f"{family.label} {index + 1} ({title})"

        namesakes = by_name.get(_norm(title), [])
        if family.by_index:
            node_id = f"{family.id_prefix}-{index + 1}"
            existing = nodes.get(node_id)
            if existing is not None and family.label is None and not _same_name(
                existing.name, title
            ):
                report.unmatched.append(
                    f"#{index} {title!r}: {node_id} is {existing.name!r}"
                )
                continue
        elif len(namesakes) > 1:
            report.unmatched.append(f"#{index} {title!r}: names {', '.join(namesakes)}")
            continue
        elif namesakes:
            node_id = namesakes[0]
            existing = nodes[node_id]
        else:
            node_id = f"{family.id_prefix}-{slugify(title)}"
            existing = None

        if node_id in taken:
            report.unmatched.append(f"#{index} {title!r}: {node_id} is already mapped")
            continue
        if existing is None:
            if family.add_as is None:
                report.unmatched.append(f"#{index} {title!r}: no node")
                continue
            if node_id in nodes or any(i != node_id for i in namesakes):
                clash = node_id if node_id in nodes else namesakes[0]
                report.unmatched.append(f"#{index} {title!r}: clashes with {clash}")
                continue
            report.added += 1
        else:
            report.matched += 1
            if family.label is None and _norm(existing.name) != _norm(title):
                report.renamed.append(f"{node_id}: {existing.name!r} -> {title!r}")

        taken.add(node_id)
        desc = entry.get("desc")
        mapped.append(
            GameNode(
                id=node_id,
                name=name,
                description=readable(desc) if desc else None,
                system=family.system if existing is None else None,
                kind=family.add_as if existing is None else None,
            )
        )
    return mapped, report


def map_catalog(
    families: Mapping[str, Iterable[Mapping[str, Any]]],
    nodes: Iterable[Node],
    buildid: str | None,
) -> tuple[GameData, dict[str, FamilyReport], list[str]]:
    """Return the game file, a report per mapped family, and the skipped families."""
    by_id = {n.id: n for n in nodes}
    game = GameData(buildid=buildid)
    reports: dict[str, FamilyReport] = {}
    for prefix, family in FAMILIES.items():
        if prefix not in families:
            continue
        mapped, reports[prefix] = _map_family(family, families[prefix], by_id)
        game.nodes.extend(mapped)
    skipped = [prefix for prefix in families if prefix not in FAMILIES]
    return game, reports, skipped


def to_yaml(game: GameData) -> str:
    doc = {
        "buildid": game.buildid,
        "nodes": [n.model_dump(mode="json", exclude_none=True) for n in game.nodes],
    }
    return GAME_FILE_HEADER + yaml.safe_dump(
        doc, sort_keys=False, allow_unicode=True, width=1_000_000
    )
