"""Read the game's own English strings out of a local Revolution Idle install.

Only the two Unity Localization bundles are opened: the shared-data bundle maps
each entry id to its key, and the English bundle maps the same id to its text.
`resources.assets` is never touched, because its TextAssets include developer
test saves, some named after real players.

The game stores effect templates with `{0}` placeholders, so no number in the
output is a game value.
"""

import json
import re
from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Any

import yaml

STEAM_APP_ID = "2763740"
DEFAULT_INSTALL = Path(
    r"C:\Program Files (x86)\Steam\steamapps\common\Revolution Idle"
)
BUNDLE_DIR = Path(
    "Revolution Idle_Data", "StreamingAssets", "aa", "StandaloneWindows64"
)
SHARED_BUNDLE = "localization-assets-shared_assets_all.bundle"
ENGLISH_BUNDLE = "localization-string-tables-english(en)_assets_all.bundle"

STRINGS_REL_PATH = Path("data", "game", "strings.en.json")
CATALOG_REL_PATH = Path("data", "game", "catalog.yaml")

_NAME_KEY = re.compile(r"(?P<prefix>.+)_NAME_(?P<index>\d+)")
_DESC_KEY = re.compile(r"(?P<prefix>.+)_DESC_(?P<index>\d+)")

CATALOG_HEADER = (
    "# Generated by `atlas game` from a local game install. Local only: not\n"
    "# committed. Texts are templates; `{0}` marks where the game inserts a number.\n"
)


class GameError(Exception):
    pass


def pair_tables(
    shared: Mapping[int, Mapping[str, Any]], tables: Iterable[Mapping[str, Any]]
) -> dict[str, str]:
    """Join each string table's entries to their keys.

    `shared` maps a shared-data object's path id to its typetree; each table
    names its shared data by that path id in `m_SharedData`.
    """
    strings: dict[str, str] = {}
    for table in tables:
        name = table["m_Name"]
        path_id = table["m_SharedData"]["m_PathID"]
        if path_id not in shared:
            raise GameError(f"table {name!r}: shared data {path_id} not found")
        keys = {entry["m_Id"]: entry["m_Key"] for entry in shared[path_id]["m_Entries"]}
        for entry in table["m_TableData"]:
            key = keys.get(entry["m_Id"])
            if key is None:
                raise GameError(f"table {name!r}: entry id {entry['m_Id']} has no key")
            if key in strings:
                raise GameError(f"table {name!r}: key {key!r} appears in two tables")
            strings[key] = entry["m_Localized"]
    return strings


def find_families(strings: Mapping[str, str]) -> dict[str, list[dict[str, Any]]]:
    """Group `<PREFIX>_NAME_<n>` / `<PREFIX>_DESC_<n>` keys by prefix.

    A prefix is a family once at least one index has both keys. Every index
    seen under that prefix is listed, with null for a missing half, so a
    relic missing its description is visible rather than silently absent.
    """
    names: dict[str, dict[int, str]] = {}
    descs: dict[str, dict[int, str]] = {}
    for key, text in strings.items():
        for pattern, bucket in ((_NAME_KEY, names), (_DESC_KEY, descs)):
            match = pattern.fullmatch(key)
            if match:
                bucket.setdefault(match["prefix"], {})[int(match["index"])] = text

    families: dict[str, list[dict[str, Any]]] = {}
    for prefix in sorted(names.keys() & descs.keys()):
        by_name, by_desc = names[prefix], descs[prefix]
        if not by_name.keys() & by_desc.keys():
            continue
        families[prefix] = [
            {"index": i, "name": by_name.get(i), "desc": by_desc.get(i)}
            for i in sorted(by_name.keys() | by_desc.keys())
        ]
    return families


def read_buildid(install: Path) -> str | None:
    manifest = install.parent.parent / f"appmanifest_{STEAM_APP_ID}.acf"
    if not manifest.is_file():
        return None
    match = re.search(r'"buildid"\s+"(\d+)"', manifest.read_text(encoding="utf-8"))
    return match[1] if match else None


def read_install(install: Path) -> dict[str, Any]:
    """Return `{"buildid", "unity", "strings"}` read from a game install."""
    if not install.is_dir():
        raise GameError(f"game install not found: {install} (pass --install PATH)")
    bundle_dir = install / BUNDLE_DIR
    for bundle in (SHARED_BUNDLE, ENGLISH_BUNDLE):
        if not (bundle_dir / bundle).is_file():
            raise GameError(f"localization bundle not found: {bundle_dir / bundle}")
    try:
        import UnityPy
    except ImportError:
        raise GameError(
            "UnityPy is not installed; run `uv sync --extra game`"
        ) from None

    shared = {
        obj.path_id: obj.read_typetree()
        for obj in UnityPy.load(str(bundle_dir / SHARED_BUNDLE)).objects
        if obj.type.name == "MonoBehaviour"
    }
    english = [
        obj
        for obj in UnityPy.load(str(bundle_dir / ENGLISH_BUNDLE)).objects
        if obj.type.name == "MonoBehaviour"
    ]
    if not english:
        raise GameError(f"no string tables in {ENGLISH_BUNDLE}")
    return {
        "buildid": read_buildid(install),
        "unity": english[0].assets_file.unity_version,
        "strings": pair_tables(shared, (obj.read_typetree() for obj in english)),
    }


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def write_outputs(
    root: Path, dump: Mapping[str, Any], families: Mapping[str, list[dict[str, Any]]]
) -> None:
    strings_doc = {
        "buildid": dump["buildid"],
        "unity": dump["unity"],
        "strings": dict(sorted(dump["strings"].items())),
    }
    _write(
        root / STRINGS_REL_PATH,
        json.dumps(strings_doc, indent=2, ensure_ascii=False) + "\n",
    )
    catalog_doc = {
        "buildid": dump["buildid"],
        "unity": dump["unity"],
        "families": dict(families),
    }
    _write(
        root / CATALOG_REL_PATH,
        CATALOG_HEADER
        + yaml.safe_dump(
            catalog_doc, sort_keys=False, allow_unicode=True, width=1_000_000
        ),
    )
